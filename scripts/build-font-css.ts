/**
 * Writes src/fonts/kuronuri.css: the @font-face rules for the Japanese
 * font (Kuronuri, pixel level 35, from @lihbr/kuronuri, OFL; decision D41),
 * keeping only the regular weight the game uses. The package's own
 * stylesheet also carries italic and bold, which makes it three times the
 * size (89 KB against 29 KB gzipped). Each rule covers a range of
 * characters, so a browser downloads only the slices a page shows.
 *
 * Run by `npm run dev` and `npm run build`, like the decks, so the file
 * is never committed.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** How pixelated the font is, from 0 (smooth) to 100 (blockiest); 35 since playtest feedback found 70 hard to read (D41). */
const PIXEL_LEVEL = 35;
const OUTPUT = 'src/fonts/kuronuri.css';

const packageCss = fileURLToPath(
  import.meta.resolve(`@lihbr/kuronuri/kuronuri-${PIXEL_LEVEL}.css`),
);
const filesUrl = `../../node_modules/@lihbr/kuronuri/dist/web/files/`;

const rules = readFileSync(packageCss, 'utf8').match(/@font-face\s*\{[^}]*\}/g) ?? [];
const regular = rules
  .filter((rule) => rule.includes('font-style: normal') && rule.includes('font-weight: 400'))
  .map((rule) => rule.replaceAll('url("files/', `url("${filesUrl}`));

if (regular.length === 0) {
  throw new Error(`No regular @font-face rules in ${packageCss}: has @lihbr/kuronuri changed?`);
}

mkdirSync('src/fonts', { recursive: true });
writeFileSync(
  OUTPUT,
  `/* Generated by scripts/build-font-css.ts from @lihbr/kuronuri (OFL); do not edit. */\n${regular.join('\n')}\n`,
);
console.log(`Wrote ${OUTPUT}: ${regular.length} character ranges of Kuronuri ${PIXEL_LEVEL}.`);
